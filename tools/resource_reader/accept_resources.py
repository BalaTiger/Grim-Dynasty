"""Integration acceptance; reads authorized installation, writes only JSON report.

Run with --output <new-json-path>. Official exports, when present, are compared
but never generated by this script. No game process or DLL is loaded.
"""
import argparse, hashlib, json, math
from pathlib import Path
from gd_resources import ARZ, ARC, GAME_ROOT, quest_record, references

SAMPLES={'mastery':'records/skills/playerclass01/_classtraining_class01.dbr','equipment':'records/items/gearweapons/swords1h/b000_sword.dbr','quest_item':'records/items/questitems/scrapmetal.dbr'}
QUEST='gdareab/mq_murdersandworse.qst'

def digest(path):return hashlib.file_digest(path.open('rb'),'sha256').hexdigest()

def compare_dbr(record,path):
    rows={}
    for line in path.read_text(encoding='utf-8-sig').splitlines():
        if not line:continue
        field,rest=line.split(',',1)
        if not rest.endswith(','):raise AssertionError('Invalid official DBR row')
        rows[field]=rest[:-1]
    assert set(rows)==set(record['fields']),('Field names differ',len(rows),len(record['fields']))
    for field,v in record['fields'].items():
        values=v if isinstance(v,list) else [v]
        # Official text uses semicolons for typed arrays, commas remain in strings.
        exported=rows[field].split(';') if record['field_types'][field]!=2 or len(values)>1 else [rows[field]]
        assert len(exported)==len(values),(field,exported,values)
        for x,y in zip(values,exported):
            if isinstance(x,float):assert math.isclose(x,float(y),rel_tol=0.000005,abs_tol=0.000005),(field,x,y)
            elif isinstance(x,int):assert x==int(y),(field,x,y)
            else:assert x==y,(field,x,y)
    return {'all_fields_match':True,'fields_compared':len(rows),'float_comparison':'official decimal serialization, relative/absolute tolerance 5e-6'}

def run(official):
    paths=[GAME_ROOT/'database/database.arz',GAME_ROOT/'resources/Text_EN.arc',GAME_ROOT/'resources/Quests.arc',GAME_ROOT/'ArchiveTool.exe']
    before={str(p):digest(p) for p in paths}
    with ARZ.open(paths[0]) as db,ARC.open(paths[1]) as text,ARC.open(paths[2]) as quests:
        tags,locations=text.tags(); samples={}
        for label,name in SAMPLES.items():
            r=db.record(name)
            resolved=[{**ref,'text':tags.get(ref['target']),'source':locations.get(ref['target'])} for ref in references(r) if ref['kind']=='tag']
            samples[label]={'record':name,'class':r['class'],'field_count':len(r['fields']),'body_sha256':r['body_sha256'],'resolved_tags':resolved}
            export=official/({'mastery':'mastery.dbr','equipment':'sword.dbr','quest_item':'scrap.dbr'}[label])
            if export.exists():samples[label]['official_comparison']=compare_dbr(r,export)
        q=quest_record(quests.read(QUEST))
        q['member']=QUEST
        q['resolved_record_candidates']=[{'target':x['text'],'present_in_base_database':x['text'].casefold() in db.records} for x in q['resource_reference_candidates'] if x['text'].lower().endswith('.dbr')]
        checked_quests=0
        for name in quests.entries:
            quest_record(quests.read(name));checked_quests+=1
        for name in text.entries:text.read(name)
        cross=[]
        for container,member,relative in [(text,'tags_skills.txt','tags/tags_skills.txt'),(text,'tags_items.txt','tags/tags_items.txt'),(quests,QUEST,'quest/'+QUEST)]:
            p=official/relative
            if p.exists():
                expected=hashlib.sha256(container.read(member)).hexdigest();actual=digest(p)
                assert expected==actual,member
                cross.append({'member':member,'official_bytes_equal':True,'sha256':actual})
        result={'status':'passed','database_index_records':len(db.records),'text_archive_entries_checked':len(text.entries),'resolved_base_tags':len(tags),'quest_archive_entries_checked':checked_quests,'samples':samples,'quest':q,'official_arc_comparisons':cross,'coverage':{'database':'complete base index; selected records, not all record bodies','arc':'all base English-text and quest members checked including Adler32','qst':'all base localization directories; graph opcodes remain opaque','dlc':'not merged; base samples only','host':'no game launch, DLL load or standalone host test'},'input_sha256_before':before}
    after={str(p):digest(p) for p in paths}
    assert before==after,'Source resource changed during acceptance'
    result['source_hashes_unchanged']=True
    return result

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--output',required=True);ap.add_argument('--official',type=Path,default=Path(r'D:\MyGitRepo\Grim-Dynasty\.tooling\resource-reader-validation'));a=ap.parse_args()
    result=run(a.official)
    with Path(a.output).open('x',encoding='utf8') as f:json.dump(result,f,ensure_ascii=False,indent=2)
    print(json.dumps({k:v for k,v in result.items() if k in ('status','database_index_records','text_archive_entries_checked','resolved_base_tags','quest_archive_entries_checked','source_hashes_unchanged')},indent=2))
