using System;
using GrimDynasty.CombatRuntime;

// Only own conditional getter and changed settlement-hook paths. This entry
// does not rerun the accepted NativeDamageSettlementTests or start a scene.
public static class NativeAttributeGetterTests {
 static int assertions,groups;
 static void Need(bool value,string why){assertions++;if(!value)throw new Exception(why);}
 static void Group(string name,Action test){int before=assertions;test();groups++;Console.WriteLine("PASS "+name+": "+(assertions-before)+" assertions");}
 static float F(uint bits){return BitConverter.ToSingle(BitConverter.GetBytes(bits),0);}
 static uint Bits(float value){return unchecked((uint)BitConverter.ToInt32(BitConverter.GetBytes(value),0));}
 static NativeAttributeConstants Snapshot(){return NativeAttributeConstants.FromRecordedSnapshot();}
 static void Map(NativeAttributeView v,int index,float a,float b,float c){long at=4L*index;v.SetObservedFloat(at,a);v.SetObservedFloat(at+0xE8,b);v.SetObservedFloat(at+0x1D0,c);}
 static NativeAttributeResult Run(NativeAttributeView v,int? index=0){return NativeAttributeGetter.Evaluate(v,index,Snapshot(),true,true);}
 static void Stop(NativeAttributeResult r,string reason,uint at,int fields,int constants){
  Need(r.Status==NativeAttributeStatus.Unsupported&&r.Reason==reason&&r.ResumeInstructionRva==at&&!r.ReturnedBits.HasValue,"precise coverage stop: "+reason);
  Need(r.FieldReads==fields&&r.ConstantReads==constants,"lazy observation prefix: "+reason);
 }
 static void LazyReadsAndConditions(){
  var v=new NativeAttributeView();
  var r=Run(v);Stop(r,"UnknownCField",0x0CF6EE,1,1);
  Need(r.FailingOffset==0x1D0&&!r.ObservedAOffset.HasValue&&!r.ObservedBOffset.HasValue,"C is the first memory field, despite formula naming A first");
  v.SetObservedFloat(0x1D0,0);r=Run(v);Stop(r,"UnknownAField",0x0CF6F7,2,1);
  v.SetObservedFloat(0,1);r=Run(v);Stop(r,"UnknownBField",0x0CF70B,3,2);
  Need(r.CPlusOneBits==0x3F800000U&&r.ScaledCBits==0x42C80000U&&!r.MultiplierBits.HasValue,"C arithmetic completed before the B load; MAXSS follows it");
  v.SetObservedFloat(0xE8,0);
  r=NativeAttributeGetter.Evaluate(v,0,Snapshot(),true,false);Stop(r,"FloatingPointEnvironmentUnobserved",0x0CF6FC,2,1);
  r=NativeAttributeGetter.Evaluate(v,null,Snapshot(),true,true);Stop(r,"UnknownSignedIndex",0x0CF6EB,0,1);
  r=NativeAttributeGetter.Evaluate(v,0,Snapshot(),false,true);Stop(r,"ConstantSnapshotApplicabilityUnobserved",0x0CF6E0,0,0);
  var missingK1=new NativeAttributeConstants(0x3F800000,null,0x3C23D70A);
  v.SetObservedFloat(0,-1);r=NativeAttributeGetter.Evaluate(v,0,missingK1,true,true);Stop(r,"UnknownK1Constant",0x0CF703,2,2);
  v.SetObservedBits(0xE8,null);r=Run(v);Stop(r,"UnknownBField",0x0CF70B,3,2);
  v.SetObservedFloat(0xE8,Single.NaN);r=Run(v);Stop(r,"NegativeBaseBranchOutsideCoverage",0x0CF718,3,2);
  Need(r.MultiplierBits==0x42C80000U&&!r.ScaledBBits.HasValue,"negative base still loads B and computes M, but has not used B arithmetically or read K2");
  v.SetObservedFloat(0,0);r=Run(v);Stop(r,"NonfiniteScaledBOperandOutsideCoverage",0x0CF71A,3,3);
  v.SetObservedFloat(0xE8,0);
  r=NativeAttributeGetter.Evaluate(v,0,new NativeAttributeConstants(0x3F800000,0x42C80000,null),true,true);Stop(r,"UnknownK2Constant",0x0CF71A,3,3);
 }
 static void SignedOffsetsAndAliases(){
  var v=new NativeAttributeView();var r=Run(v,Int32.MinValue);
  Need(r.FailingOffset==-8589934128L&&r.ResumeInstructionRva==0x0CF6EE,"minimum signed index uses Int64 offset, not unsigned/int wrapping");
  r=Run(v,Int32.MaxValue);Need(r.FailingOffset==8589935052L&&r.ResumeInstructionRva==0x0CF6EE,"maximum signed index offset remains exact");
  v.SetObservedFloat(0x1CC,0);r=Run(v,-1);
  Need(r.FieldReads==2&&r.FailingOffset==-4&&r.ResumeInstructionRva==0x0CF6F7,"negative index can read its observed C before an unobserved A");
  Map(v,-1,1,0,0);r=Run(v,-1);
  Need(r.Status==NativeAttributeStatus.ConditionalNormalReturn&&r.ReturnedBits==0x3F800000U,"explicit own negative-offset observations are accepted without inventing native index bounds");
  Map(v,58,1,0,0);r=Run(v,58);
  Need(r.Status==NativeAttributeStatus.ConditionalNormalReturn&&r.ObservedAOffset==0xE8&&r.ObservedBOffset==0x1D0&&r.ObservedCOffset==0x2B8,"spacing 0xE8 does not establish a 58-element bounds check");
  v.SetObservedFloat(0xE8,3);r=Run(v,58);
  Need(r.ReturnedBits==0x40400000U&&v.ReadObservedBits(0xE8)==0x40400000U,"one shared offset aliases index58 A and index0 B, with live mutation");
  v.Invalidate();r=Run(v,58);Stop(r,"InvalidatedAttributeView",0x0CF6EE,1,1);
 }
 static void IndependentRoundingOracles(){
  // Independently derived dyadic oracles, not expected values generated by
  // calling the production arithmetic again. K2=(1-3*2^-27)/100 exactly.
  var v=new NativeAttributeView();Map(v,0,1,-100,0);var r=Run(v);
  Need(r.ScaledBBits==0xBF800000U&&r.BPlusOneBits==0U&&r.ReturnedBits==0U,"rounded -100*K2 is -1, so adding one removes the unrounded residual");
  Map(v,0,1,0,F(0x34400000));r=Run(v); // C=3*2^-24
  Need(r.CPlusOneBits==0x3F800002U&&r.ScaledCBits==0x42C80003U,"C+1 midpoint rounds to even before multiplication by100 rounds again");
  Need(r.ReturnedBits==0x3F800002U,"all native rounding steps return 1+2ULP, not the once-rounded expression");
  float incorrectlyMerged=(float)((1.0+(double)F(0x34400000))*100.0*(double)F(0x3C23D70A));
  Need(Bits(incorrectlyMerged)==0x3F800001U&&Bits(incorrectlyMerged)!=r.ReturnedBits.Value,"independent counterexample detects collapsing instruction-level rounding");
  Map(v,0,1,F(0xC2480001),0);r=Run(v); // B=-(50+2^-18)
  Need(r.ScaledBBits==0xBF000000U&&r.BPlusOneBits==0x3F000000U&&r.AfterMultiplierBits==0x42480000U&&r.ReturnedBits==0x3F000000U,"recorded binary32 K2 chooses the correct side of a half-ULP boundary");
  float wrong=(float)((double)F(0xC2480001)*0.01);wrong=(float)((double)wrong+1.0);wrong=(float)((double)wrong*100.0);wrong=(float)((double)wrong*0.01);
  Need(Bits(wrong)==0x3EFFFFFDU&&Bits(wrong)!=r.ReturnedBits.Value,"using double decimal .01 produces a genuinely different answer");
  Need(r.FieldReads==3&&r.ConstantReads==4&&r.ResumeInstructionRva==0x0CF73D,"normal path observes C/A/B and One/K1/K2/K2 before saved return");
  Need(v.ReadObservedBits(0)==0x3F800000U&&v.ReadObservedBits(0xE8)==0xC2480001U&&v.ReadObservedBits(0x1D0)==0,"getter leaves every observed source DWORD unchanged");
 }
 static void FiniteDomainAndMaxZero(){
  var v=new NativeAttributeView();Map(v,0,F(0x80000000),0,0);var r=Run(v);
  Need(r.Status==NativeAttributeStatus.ConditionalNormalReturn&&r.AfterBaseBits==0x80000000U&&r.BeforeFinalMaxBits==0x80000000U&&r.ReturnedBits==0U,"negative zero takes nonnegative branch; final MAXSS selects positive zero");
  Map(v,0,1,0,-2);r=Run(v);
  Need(r.ScaledCBits==0xC2C80000U&&r.MultiplierBits==0U&&r.ReturnedBits==0U,"negative scaled C is clamped only in the temporary multiplier");
  Map(v,0,1,-200,0);r=Run(v);
  Need(r.BeforeFinalMaxBits==0xBF800000U&&r.ReturnedBits==0U,"negative final product is clamped to positive zero");
  Map(v,0,F(1),0,0);r=Run(v);
  Need(r.AfterBaseBits==1U&&r.AfterMultiplierBits==100U&&r.ReturnedBits==1U,"gradual-underflow subnormal survives separate multiplication by100 and K2");
  Map(v,0,1,0,Single.MaxValue);r=Run(v);Stop(r,"ScaledCResultOutsideCoverage",0x0CF703,2,2);
  Need(r.CPlusOneBits==0x7F7FFFFFU&&!r.ObservedBOffset.HasValue,"overflow at C scaling stops before B read");
  Map(v,0,Single.MaxValue,100,-1);r=Run(v);Stop(r,"AfterBaseResultOutsideCoverage",0x0CF726,3,3);
  Need(r.MultiplierBits==0U&&!r.AfterBaseBits.HasValue,"zero future multiplier does not permit skipping an earlier unsupported overflow");
  Map(v,0,Single.NaN,0,0);r=Run(v);Stop(r,"NonfiniteBaseComparisonOutsideCoverage",0x0CF700,2,1);
  Map(v,0,1,0,Single.NaN);r=Run(v);Stop(r,"NonfiniteCPlusOneOperandOutsideCoverage",0x0CF6FC,2,1);
 }
 static NativeDamageState Owner(){return new NativeDamageState {Life=1,Accumulated=0,GateByte=0,Dirty=0,ThresholdMultiplier=1,ThresholdFlag=7};}
 static NativeDamageInputs Damage(){return new NativeDamageInputs(2,1,1,true);}
 static void BoundHookAndLiveFields(){
  var state=Owner();var stats=new NativeDamageStats {Type=1};var v=new NativeAttributeView();Map(v,4,1,0,0);
  var binding=new NativeAttributeSettlementBinding(state,v,Snapshot(),true,true);int finals=0;
  var hooks=new NativeDamageHooks {Attribute=binding.Observe,Final=delegate(NativeDamageState s,float damage,NativeDamageStats st){
   Need(Object.ReferenceEquals(s,state)&&Object.ReferenceEquals(st,stats)&&damage==2&&s.Life==-1&&s.Accumulated==2&&s.Dirty==1,"real settlement final sees shared state/stats and earlier write prefix");finals++;return new NativeDamageCallObservation(true);
  }};
  var r=NativeDamageSettlement.Run(state,stats,Damage(),hooks);
  Need(r.Status==NativeDamageStatus.ConditionalNormalReturn&&r.ThresholdFlagWritten&&finals==1&&binding.LastResult.ReturnedBits==0x3F800000U,"actual getter value 1 controls the existing property4 threshold comparison");
  Need(Object.ReferenceEquals(binding.Fields,v)&&Object.ReferenceEquals(binding.LastResult.Fields,v)&&binding.LastResult.Index==4&&binding.LastResult.ObservedCOffset==0x1E0,"binding retains live owner+F78 attribute view and actual numeric index4");
  state=Owner();v=new NativeAttributeView();Map(v,4,1,0,0);binding=new NativeAttributeSettlementBinding(state,v,Snapshot(),true,true);
  hooks=new NativeDamageHooks {
   Gate=delegate(NativeDamageState s){Need(Object.ReferenceEquals(s,state),"gate shares the bound owner");v.SetObservedFloat(0x10,4);return new NativeDamageObservation<byte>(true,0);},
   Attribute=binding.Observe,Final=delegate(NativeDamageState s,float damage,NativeDamageStats st){return new NativeDamageCallObservation(true);}
  };
  r=NativeDamageSettlement.Run(state,stats,new NativeDamageInputs(2,0,1,true),hooks);
  Need(r.Status==NativeDamageStatus.ConditionalNormalReturn&&!r.ThresholdFlagWritten&&state.ThresholdFlag==7&&binding.LastResult.ReturnedBits==0x40800000U,"gate mutation reaches getter live; changed value4 prevents flag store without snapshots");
  var mismatched=binding.Observe(Owner(),4);
  Need(!mismatched.ReturnedNormally&&!mismatched.Value.HasValue&&binding.LastResult.Reason=="AttributeOwnerBindingMismatch"&&binding.LastResult.FieldReads==0,"other owner cannot use a successful observation from this binding");
  Need(binding.Evaluations==2,"binding counts its own getter/owner-check attempts only");
 }
 static void SettlementFailurePrefixes(){
  var state=Owner();var stats=new NativeDamageStats {Type=1};var v=new NativeAttributeView();var binding=new NativeAttributeSettlementBinding(state,v,Snapshot(),true,true);
  var hooks=new NativeDamageHooks {Attribute=binding.Observe};
  var r=NativeDamageSettlement.Run(state,stats,Damage(),hooks);
  Need(r.Status==NativeDamageStatus.Unsupported&&r.Reason=="AttributeReturnUnobserved"&&r.ResumeInstructionRva==0x068B60&&r.StoreInstructions==3&&r.FinalCalls==0,"unresolved getter stops real settlement after three stores and before final callback");
  Need(binding.LastResult.Reason=="UnknownCField"&&binding.LastResult.ResumeInstructionRva==0x0CF6EE&&binding.LastResult.FailingOffset==0x1E0&&state.Life==-1&&state.Accumulated==2&&state.Dirty==1&&state.ThresholdFlag==7,"inner getter diagnosis and outer mutation prefix both survive failure");
  state=Owner();Map(v,4,-1,0,0);binding=new NativeAttributeSettlementBinding(state,v,Snapshot(),true,true);hooks.Attribute=binding.Observe;
  r=NativeDamageSettlement.Run(state,stats,Damage(),hooks);
  Need(r.Status==NativeDamageStatus.Unsupported&&binding.LastResult.Reason=="NegativeBaseBranchOutsideCoverage"&&binding.LastResult.ResumeInstructionRva==0x0CF718&&binding.LastResult.FieldReads==3&&r.StoreInstructions==3,"negative getter branch is not replaced with zero/normal return");
  state=Owner();Map(v,4,1,0,0);binding=new NativeAttributeSettlementBinding(state,v,Snapshot(),true,true);hooks.Attribute=binding.Observe;
  r=NativeDamageSettlement.Run(state,stats,Damage(),hooks);
  Need(r.Status==NativeDamageStatus.Unsupported&&r.Reason=="MissingFinalInterface"&&r.StoreInstructions==4&&state.ThresholdFlag==1&&binding.LastResult.Status==NativeAttributeStatus.ConditionalNormalReturn,"closed getter does not manufacture a normal final callback or complete combat");
  state=Owner();binding=new NativeAttributeSettlementBinding(state,v,Snapshot(),true,true);hooks.Attribute=binding.Observe;
  r=NativeDamageSettlement.Run(state,stats,new NativeDamageInputs(2,0,1,true),hooks);
  Need(r.Reason=="MissingGateInterface"&&r.StoreInstructions==0&&binding.Evaluations==0,"binding does not manufacture the unresolved gate callback either");
 }
 public static int Main(){
  try{
   Group("actual read order and conditions",LazyReadsAndConditions);
   Group("signed offsets and shared aliases",SignedOffsetsAndAliases);
   Group("independent binary32 rounding oracles",IndependentRoundingOracles);
   Group("finite domain and positive zero max",FiniteDomainAndMaxZero);
   Group("bound getter and live mutation",BoundHookAndLiveFields);
   Group("settlement failure prefix integration",SettlementFailurePrefixes);
   Console.WriteLine("PASS NativeAttributeGetter: "+assertions+" assertions / "+groups+" groups");return 0;
  }catch(Exception e){Console.Error.WriteLine("FAIL NativeAttributeGetter: "+e);return 1;}
 }
}
